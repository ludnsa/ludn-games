/**
 * وصف بطاقة الدور وقت كشف الأدوار: أول سطرين من شرح الدور في التعليمات.
 * الشيخ: سطره الأول ينتهي بـ "يختار طريقة النقاش:"، فيطلع معه الخياران (لو طلع سطرين بس، يطلع خيار واحد ويختفي الثاني).
 */
export function mafiaRoleCardLines(role: MafiaRole): string[] {
  const r = ROLES.find((x) => x.id === role);
  if (!r) return [MAFIA_ROLES[role].description];
  const lines = [...(r.body ? [r.body] : []), ...(r.points ?? []).map((p) => (typeof p === "string" ? p : p.text))];
  return role === "sheikh" ? lines : lines.slice(0, 2);
}

