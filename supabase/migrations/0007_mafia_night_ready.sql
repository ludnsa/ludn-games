--
-- طريقة التشغيل: انسخه والصقه في Supabase SQL Editor ثم شغّله.
-- قابل لإعادة التشغيل. لو ما انشغّل، اللعبة تشتغل عادي بس بدون العداد.
-- =====================================================================

alter table public.mafia_rooms
  add column if not exists night_ready jsonb;
